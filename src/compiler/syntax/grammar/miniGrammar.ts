import { E, EOF_SYMBOL, N, T, type Grammar, type Production } from "./grammarTypes";

function production(id: string, lhs: string, rhs: ReturnType<typeof T>[]): Production {
  return { id, lhs, rhs, label: `${lhs} -> ${rhs.map((symbol) => symbol.name).join(" ")}` };
}

const p = (id: string, lhs: string, rhs: Production["rhs"]): Production => ({
  id,
  lhs,
  rhs,
  label: `${lhs} -> ${rhs.map((symbol) => symbol.name).join(" ")}`
});

